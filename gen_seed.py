import random

def gen_book_insert(books, start_no, category_name):
    result = f"-- {category_name}\n"
    result += "INSERT INTO `book` (`book_no`, `isbn`, `name`, `author`, `publisher`, `publish_date`, `category_id`, `description`, `detail`, `price`, `sale_price`, `cost_price`, `stock`, `sales_count`, `status`, `recommend_status`) VALUES\n"
    values = []
    for i, (name, author, publisher, date, cat_id, desc, detail, price, sale, cost, stock) in enumerate(books):
        no = start_no + i
        isbn = f"978-7-{random.randint(100, 999):03d}-{no:05d}"
        sales = random.randint(5, 300)
        status = 1
        recommend = 1 if random.random() < 0.3 else 0
        values.append(f"('BK{no:03d}', '{isbn}', '{name}', '{author}', '{publisher}', '{date}', {cat_id}, '{desc}', '{detail}', {price:.2f}, {sale:.2f}, {cost:.2f}, {stock}, {sales}, {status}, {recommend})")
    result += ",\n".join(values) + ";\n\n"
    return result

